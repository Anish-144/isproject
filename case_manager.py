# case_manager.py — Case Management + Enterprise PDF generation for SOC Dashboard
import json, os, datetime, textwrap
from fpdf import FPDF

CASES_FILE = os.path.join("logs", "cases.json")


def _load_cases():
    if not os.path.exists(CASES_FILE):
        return []
    try:
        with open(CASES_FILE, "r") as f:
            return json.load(f)
    except (json.JSONDecodeError, IOError):
        return []


def _save_cases(cases):
    os.makedirs(os.path.dirname(CASES_FILE), exist_ok=True)
    with open(CASES_FILE, "w") as f:
        json.dump(cases, f, indent=2, default=str)


def get_cases():
    return _load_cases()


def create_case(title, severity, description, log_index=-1, extra=None):
    cases = _load_cases()
    case = {
        "id": len(cases) + 1,
        "title": title,
        "severity": severity,
        "status": "Open",
        "description": description,
        "log_index": log_index,
        "created_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        "updated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
    }
    if extra:
        case.update(extra)
    cases.append(case)
    _save_cases(cases)
    return case


def update_case_status(case_id, new_status):
    cases = _load_cases()
    for c in cases:
        if c["id"] == case_id:
            c["status"] = new_status
            c["updated_at"] = datetime.datetime.now(datetime.timezone.utc).isoformat()
            _save_cases(cases)
            return True
    return False


